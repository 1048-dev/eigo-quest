// Build the change table from applied.json (markdown rows) + counts
import fs from "node:fs";
import path from "node:path";
import { REPO } from "./lib.mjs";
const ap = JSON.parse(fs.readFileSync(path.join(REPO, ".run9-w3738/applied.json"), "utf8"));
const esc = (s) => String(s).replace(/\|/g, "\\|").replace(/\n/g, " ");
const rows = [...ap].sort((a, b) => a.lesson - b.lesson || a.file.localeCompare(b.file));
const out = ["| L | 欄 | before | after | reviewers | reason |", "|---:|---|---|---|---|---|"];
for (const p of rows) out.push(`| ${p.lesson} | \`${p.path}\` | ${esc(p.before)} | ${esc(p.after)} | ${esc(p.reviewers)} | ${esc(p.reason)} |`);
fs.writeFileSync(path.join(REPO, ".run9-w3738/table.md"), out.join("\n") + "\n");
const fields = new Set(ap.map((p) => `${p.lesson}|${p.path}`));
const lessons = new Set(ap.map((p) => p.lesson));
const byFile = {};
for (const p of ap) byFile[p.file] = (byFile[p.file] ?? 0) + 1;
const byFileFields = {};
for (const p of ap) (byFileFields[p.file] ??= new Set()).add(`${p.lesson}|${p.path}`);
console.log({ patches: ap.length, fields: fields.size, lessons: lessons.size, byFile, byFileFields: Object.fromEntries(Object.entries(byFileFields).map(([k, v]) => [k, v.size])) });
const unchanged = [];
for (let n = 1081; n <= 1140; n++) if (!lessons.has(n)) unchanged.push(n);
console.log("unchanged lessons:", unchanged.join(","));
